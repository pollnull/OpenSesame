const preferred = (navigator.languages?.[0] || navigator.language || 'en').slice(0, 2).toLowerCase();
const lang = preferred in STRINGS ? preferred : 'en';
document.documentElement.lang = lang;

function t(key, vars = {}) {
  const text = STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (match, name) => (name in vars ? vars[name] : match));
}

// Fill the static page. HTML strings above are ours, never user input.
for (const element of document.querySelectorAll('[data-i18n]')) element.textContent = t(element.dataset.i18n);
for (const element of document.querySelectorAll('[data-i18n-html]')) element.innerHTML = t(element.dataset.i18nHtml);
for (const [attribute, data] of [['aria-label', 'i18nAria'], ['title', 'i18nTitle'], ['placeholder', 'i18nPlaceholder']]) {
  for (const element of document.querySelectorAll(`[data-${data.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`)}]`)) {
    element.setAttribute(attribute, t(element.dataset[data]));
  }
}
document.body.dataset.drop = t('drop');
